#!/usr/bin/env python3
"""Generates C++ font bitmap data from LiberationSans-Bold.ttf for frw-cal ESP32."""

import sys
from pathlib import Path
from PIL import Image, ImageFont, ImageDraw

PROJECT_ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = PROJECT_ROOT / "assets" / "fonts" / "LiberationSans-Bold.ttf"

# Characters to include
PORTUGUESE_CHARS = "ÀÁÂÃÉÊÍÓÔÕÚÇàáâãéêíóôõúçºª·"
ASCII_PRINTABLE = "".join(chr(c) for c in range(32, 127))
FULL_CHARSET = sorted(list(set(ASCII_PRINTABLE + PORTUGUESE_CHARS)))
NUMERIC_CHARSET = sorted(list(set("0123456789 -/")))

def generate_font_struct(font_size: int, charset: list, font_var_name: str):
    font = ImageFont.truetype(str(FONT_PATH), font_size)
    
    # Calculate global ascent / descent
    ascent, descent = font.getmetrics()
    line_height = ascent + descent
    
    glyphs = []
    bitmaps = []
    
    for ch in charset:
        cp = ord(ch)
        bbox = font.getbbox(ch)
        length = font.getlength(ch)
        advance = max(1, round(length))
        
        bw = max(0, bbox[2] - bbox[0])
        bh = max(0, bbox[3] - bbox[1])
        x_offset = bbox[0]
        y_offset = bbox[1]
        
        # Space or empty glyph
        if bw == 0 or bh == 0:
            glyphs.append({
                "codepoint": cp,
                "width": 0,
                "height": 0,
                "xOffset": 0,
                "yOffset": 0,
                "xAdvance": advance,
                "dataOffset": len(bitmaps),
            })
            continue
        
        # Render glyph onto a 1-bit image
        im = Image.new("1", (bw + 10, bh + 10), 0) # 0 is black (background)
        draw = ImageDraw.Draw(im)
        draw.text((-bbox[0], -bbox[1]), ch, font=font, fill=1) # 1 is white (foreground)
        cropped = im.crop((0, 0, bw, bh))
        
        data_offset = len(bitmaps)
        
        # Pack 1-bit MSB first row-by-row
        row_bytes = (bw + 7) // 8
        for y in range(bh):
            for byte_idx in range(row_bytes):
                byte_val = 0
                for bit in range(8):
                    px = byte_idx * 8 + bit
                    if px < bw and cropped.getpixel((px, y)) == 1:
                        byte_val |= (0x80 >> bit)
                bitmaps.append(byte_val)
        
        glyphs.append({
            "codepoint": cp,
            "width": bw,
            "height": bh,
            "xOffset": x_offset,
            "yOffset": y_offset,
            "xAdvance": advance,
            "dataOffset": data_offset,
        })
    
    # Sort glyphs by codepoint for fast binary search
    glyphs.sort(key=lambda g: g["codepoint"])
    
    return {
        "var_name": font_var_name,
        "size": font_size,
        "ascent": ascent,
        "descent": descent,
        "line_height": line_height,
        "glyphs": glyphs,
        "bitmaps": bitmaps,
    }


def main():
    if not FONT_PATH.exists():
        print(f"Error: font not found at {FONT_PATH}")
        sys.exit(1)
        
    fonts = [
        generate_font_struct(44, NUMERIC_CHARSET, "Font_LiberationSans_Bold_44"),
        generate_font_struct(18, FULL_CHARSET, "Font_LiberationSans_Bold_18"),
        generate_font_struct(16, FULL_CHARSET, "Font_LiberationSans_Bold_16"),
        generate_font_struct(14, FULL_CHARSET, "Font_LiberationSans_Bold_14"),
        generate_font_struct(12, FULL_CHARSET, "Font_LiberationSans_Bold_12"),
    ]
    
    out_path = PROJECT_ROOT / "firmware" / "src" / "fonts_data.h"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/generate_fonts.py. DO NOT EDIT DIRECTLY.\n")
        f.write("#pragma once\n\n")
        f.write("#include <Arduino.h>\n")
        f.write("#include \"fonts.h\"\n\n")
        
        for font_data in fonts:
            var = font_data["var_name"]
            f.write(f"// --- {var} (size {font_data['size']}px) ---\n")
            
            # Write bitmap array in PROGMEM
            f.write(f"static const uint8_t {var}_bitmaps[] PROGMEM = {{\n")
            bitmaps = font_data["bitmaps"]
            for i in range(0, len(bitmaps), 16):
                chunk = bitmaps[i:i+16]
                f.write("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
            f.write("};\n\n")
            
            # Write glyph defs in PROGMEM
            f.write(f"static const GlyphDef {var}_glyphs[] PROGMEM = {{\n")
            for g in font_data["glyphs"]:
                f.write(
                    f"    {{ 0x{g['codepoint']:04X}, {g['width']}, {g['height']}, "
                    f"{g['xOffset']}, {g['yOffset']}, {g['xAdvance']}, {g['dataOffset']} }},\n"
                )
            f.write("};\n\n")
            
            # Write FontDef struct
            f.write(f"const FontDef {var} = {{\n")
            f.write(f'    "{var}",\n')
            f.write(f"    {font_data['size']},\n")
            f.write(f"    {font_data['ascent']},\n")
            f.write(f"    {font_data['descent']},\n")
            f.write(f"    {font_data['line_height']},\n")
            f.write(f"    {len(font_data['glyphs'])},\n")
            f.write(f"    {var}_glyphs,\n")
            f.write(f"    {var}_bitmaps\n")
            f.write("};\n\n")
            
    print(f"Generated font data written to {out_path}")
    for fd in fonts:
        print(f"  {fd['var_name']}: {len(fd['glyphs'])} glyphs, {len(fd['bitmaps'])} bytes bitmap")

if __name__ == "__main__":
    main()
